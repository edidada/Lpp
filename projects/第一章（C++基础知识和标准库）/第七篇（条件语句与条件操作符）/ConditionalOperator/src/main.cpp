// 导入标准库模块
import std;

// 使用标准命名空间，避免每次调用标准库函数时都需要写std::
using namespace std;

// 主函数，程序的入口
int main()
{
    // 定义一个整数变量i，并初始化为3
    int i{ 3 };

    // 使用println函数输出条件表达式的结果
    // 如果i大于2，输出"yes"，否则输出"no"
    // 这里使用了括号来明确条件表达式的优先级
    println("{}", (i > 2) ? "yes" : "no");

    // 同样使用println函数输出条件表达式的结果
    // 这里没有使用括号，但条件表达式的优先级仍然高于比较运算符
    println("{}", i > 2 ? "yes" : "no");
}